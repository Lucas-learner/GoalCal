test('Calendar creates a timed habit and edits only the selected session', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('textbox', { name: '用户名或邮箱', exact: true }).fill('preview');
  await page.getByRole('textbox', { name: '密码', exact: true }).fill('GoalCal-preview-2026!');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.goto('/app/calendar');
  const today = await page.request.get('/api/v1/today');
  expect(today.ok()).toBe(true);
  const { date } = await today.json();
  const tomorrow = new Date(`${date}T12:00:00Z`);
  tomorrow.setUTCDate(tomorrow.getUTCDate() + 1);
  const scheduledDate = tomorrow.toISOString().slice(0, 10);
  await page.getByRole('button', { name: '+ 新日程', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('开始', { exact: true }).fill(`${scheduledDate}T18:00`);
  await dialog.getByLabel('结束', { exact: true }).fill(`${scheduledDate}T18:30`);
  await dialog.getByRole('button', { name: '新习惯', exact: true }).click();
  dialog = page.getByRole('dialog');
  const title = `晚间阅读 ${Date.now()}`;
  await dialog.getByLabel('名称', { exact: true }).fill(title);
  await expect(dialog.getByLabel('开始日期')).toHaveValue(scheduledDate);
  await expect(dialog.getByLabel('默认时间（可选）')).toHaveValue('18:00');
  await dialog.getByRole('button', { name: '预览安排' }).click();
  await dialog.getByRole('button', { name: '保存习惯' }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: '日', exact: true }).click();
  await page.getByLabel('跳转日期').fill(scheduledDate);
  const block = page.locator('.gc-ev-habit').filter({ hasText: title });
  await expect(block).toContainText('18:00');
  await block.click();
  await dialog.getByRole('button', { name: '换时间', exact: true }).click();
  await dialog.getByRole('button', { name: '自定义时间 →', exact: true }).click();
  await dialog.getByLabel('开始时间（可选）').fill('19:00');
  await dialog.getByRole('button', { name: '保存安排' }).click();
  await expect(block).toContainText('19:00');
  await page.getByRole('button', { name: '下一天', exact: true }).click();
  await expect(block).toContainText('18:00');
});
