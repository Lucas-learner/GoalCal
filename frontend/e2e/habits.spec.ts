import { test, expect } from '@playwright/test';

test('habits have a mobile entry and keep Today, Calendar and history in sync', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 });
  await page.goto('/');
  await page.getByRole('textbox', { name: '用户名或邮箱', exact: true }).fill('preview');
  await page.getByRole('textbox', { name: '密码', exact: true }).fill('GoalCal-preview-2026!');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  const nav = page.getByRole('navigation', { name: '移动导航' });
  await expect(nav.getByRole('link')).toHaveText(['今天', '目标', '习惯', '日历', '设置']);
  await nav.getByRole('link', { name: '习惯', exact: true }).click();
  await expect(page.getByRole('heading', { name: '习惯', exact: true })).toBeVisible();
  await expect(nav.getByRole('link', { name: '习惯' })).toHaveAttribute('aria-current', 'page');
  expect(await nav.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);

  const title = `每日阅读 ${Date.now()}`;
  const empty = page.locator('.empty-state');
  await expect(empty.getByText('从一个想坚持的习惯开始')).toBeVisible();
  await empty.getByRole('link', { name: '+ 新习惯', exact: true }).click();
  await expect(page.getByRole('heading', { name: '你想坚持什么？', exact: true })).toBeVisible();
  const form = page.locator('form.goal-form');
  await form.getByLabel('名称', { exact: true }).fill(title);
  await form.getByRole('button', { name: '预览安排' }).click();
  await expect(form.getByText('安排预览', { exact: true })).toBeVisible();
  await form.getByRole('button', { name: '保存习惯' }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '本周节奏' })).toBeVisible();
  await expect(page.locator('.habit-week-days [aria-current="date"]')).toContainText('待完成');
  await expect(page.locator('.habit-next')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '安排时间', exact: true })).toBeVisible();
  await expect(page.getByText('习惯记录与补记')).toHaveCount(0);
  await expect(page.getByRole('link', { name: '← 返回习惯列表', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.getByRole('button', { name: '修改规则', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await form.getByLabel('预计时长（分钟）', { exact: true }).fill('35');
  await form.getByRole('button', { name: '保存修改' }).click();
  await expect(form).toHaveCount(0);

  await nav.getByRole('link', { name: '今天', exact: true }).click();
  const focusCard = page.locator('.focus-card');
  await expect(focusCard).toContainText('尚未安排时间');
  await expect(focusCard.getByRole('button', { name: '开始', exact: true })).toBeVisible();
  await expect(focusCard.getByRole('button', { name: '找时间', exact: true })).toBeVisible();
  await expect(page.locator('.habit-timeline-item').filter({ hasText: title }).getByRole('button', { name: `完成 ${title}`, exact: true })).toHaveCount(0);
  await focusCard.getByRole('button', { name: '完成', exact: true }).click();
  await expect(page.locator('.habit-timeline-item').filter({ hasText: title })).toContainText('已完成');
  const undo = page.getByRole('button', { name: '撤销', exact: true });
  await expect(undo).toBeVisible();
  await undo.click();
  await expect(focusCard.getByRole('button', { name: '完成', exact: true })).toBeVisible();

  await nav.getByRole('link', { name: '日历', exact: true }).click();
  await page.getByRole('button', { name: /尚未安排/ }).click();
  const backlogItem = page.locator('.backlog-item').filter({ hasText: title });
  await expect(backlogItem).toHaveCount(1);
  await backlogItem.getByRole('button', { name: '找时间 →' }).click();
  const details = page.getByRole('dialog');
  await expect(details).toHaveAccessibleName(title);
  await expect(details.getByRole('button', { name: '推荐空档', exact: true })).toBeVisible();
  await details.getByRole('button', { name: '返回', exact: true }).click();
  await details.getByRole('button', { name: '完成', exact: true }).click();
  await expect(page.getByText('习惯记录', { exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});

