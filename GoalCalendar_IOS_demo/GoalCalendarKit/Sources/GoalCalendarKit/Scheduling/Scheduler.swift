import Foundation

public struct SchedulingPreferences: Sendable, Hashable {
    /// Slot granularity. 30 minutes matches the product decision.
    public var gridMinutes: Int
    public var horizonDays: Int
    public var maxSuggestions: Int
    /// Don't propose something starting in the next few minutes; the user needs
    /// time to agree and get to it.
    public var leadTimeMinutes: Int

    public init(
        gridMinutes: Int = 30,
        horizonDays: Int = 14,
        maxSuggestions: Int = 3,
        leadTimeMinutes: Int = 30
    ) {
        self.gridMinutes = gridMinutes
        self.horizonDays = horizonDays
        self.maxSuggestions = maxSuggestions
        self.leadTimeMinutes = leadTimeMinutes
    }
}

public struct SchedulerCandidate: Sendable, Hashable {
    public var step: Step
    public var goal: Goal

    public init(step: Step, goal: Goal) {
        self.step = step
        self.goal = goal
    }
}

public struct SchedulerInput: Sendable {
    public var user: User
    public var now: Date
    /// Ordered by priority: the first actionable step wins.
    public var candidates: [SchedulerCandidate]
    /// Everything that occupies time within the horizon.
    public var busyEvents: [CalendarEvent]
    public var recentStates: [StateLog]
    public var preferences: SchedulingPreferences

    public init(
        user: User,
        now: Date,
        candidates: [SchedulerCandidate],
        busyEvents: [CalendarEvent],
        recentStates: [StateLog],
        preferences: SchedulingPreferences = SchedulingPreferences()
    ) {
        self.user = user
        self.now = now
        self.candidates = candidates
        self.busyEvents = busyEvents
        self.recentStates = recentStates
        self.preferences = preferences
    }
}

public struct SlotSuggestion: Sendable, Hashable {
    public var stepID: String
    public var goalID: String
    public var stepTitle: String
    public var goalTitle: String
    public var start: Date
    public var end: Date
    public var score: Double
    /// Generated by this file, never by the LLM. The user is being asked to
    /// commit real time, so the justification must be verifiable.
    public var reasons: [String]

    public init(
        stepID: String,
        goalID: String,
        stepTitle: String,
        goalTitle: String,
        start: Date,
        end: Date,
        score: Double,
        reasons: [String]
    ) {
        self.stepID = stepID
        self.goalID = goalID
        self.stepTitle = stepTitle
        self.goalTitle = goalTitle
        self.start = start
        self.end = end
        self.score = score
        self.reasons = reasons
    }

    public var interval: DateInterval { DateInterval(start: start, end: end) }
}

/// Picks when to do the next micro-step.
///
/// Deliberately a pure function of its input: no database, no clock, no model
/// call. Everything it knows arrives in `SchedulerInput`, which is what makes
/// the behaviour testable to the minute.
public struct Scheduler: Sendable {

    public init() {}

    public func suggest(_ input: SchedulerInput) -> [SlotSuggestion] {
        let state = Self.activeState(input.recentStates, now: input.now)
        let earliest = input.now.addingTimeInterval(TimeInterval(input.preferences.leadTimeMinutes * 60))
        let horizonEnd = input.now.addingTimeInterval(TimeInterval(input.preferences.horizonDays * 86_400))

        let slots = FreeTime.slots(
            user: input.user,
            events: input.busyEvents,
            from: earliest,
            to: horizonEnd
        )

        // If the highest-priority step genuinely cannot fit, fall through to the
        // next one instead of returning nothing.
        for candidate in input.candidates {
            let options = options(
                for: candidate,
                slots: slots,
                state: state,
                input: input
            )
            if !options.isEmpty {
                return Array(options.prefix(input.preferences.maxSuggestions))
            }
        }
        return []
    }

    /// The most recent state, but only if it is recent enough to describe now.
    /// A "累" logged three days ago must not shape today's recommendation.
    static func activeState(_ logs: [StateLog], now: Date) -> UserState? {
        guard let latest = logs.max(by: { $0.createdAt < $1.createdAt }) else { return nil }
        guard now.timeIntervalSince(latest.createdAt) <= 24 * 3600 else { return nil }
        return latest.state
    }

    func options(
        for candidate: SchedulerCandidate,
        slots: [DateInterval],
        state: UserState?,
        input: SchedulerInput
    ) -> [SlotSuggestion] {
        let calendar = input.user.calendar
        let need = max(15, candidate.step.estimatedMinutes)
        let needInterval = TimeInterval(need * 60)
        let grid = TimeInterval(max(5, input.preferences.gridMinutes) * 60)

        var scored: [SlotSuggestion] = []

        for slot in slots where slot.duration >= needInterval {
            var start = slot.start.roundedUp(toMinutes: input.preferences.gridMinutes, calendar: calendar)
            while start.addingTimeInterval(needInterval) <= slot.end {
                let (score, reasons) = score(
                    start: start,
                    need: need,
                    slot: slot,
                    state: state,
                    candidate: candidate,
                    input: input
                )
                scored.append(SlotSuggestion(
                    stepID: candidate.step.id,
                    goalID: candidate.goal.id,
                    stepTitle: candidate.step.title,
                    goalTitle: candidate.goal.title,
                    start: start,
                    end: start.addingTimeInterval(needInterval),
                    score: score,
                    reasons: reasons
                ))
                start = start.addingTimeInterval(grid)
            }
        }

        scored.sort { $0.score > $1.score }

        // Three variants of "15:00 and 15:30" are not real alternatives.
        var picked: [SlotSuggestion] = []
        for option in scored {
            let tooClose = picked.contains { abs($0.start.timeIntervalSince(option.start)) < 2 * 3600 }
            if tooClose { continue }
            picked.append(option)
        }
        return picked
    }

    private func score(
        start: Date,
        need: Int,
        slot: DateInterval,
        state: UserState?,
        candidate: SchedulerCandidate,
        input: SchedulerInput
    ) -> (Double, [String]) {
        let calendar = input.user.calendar
        let hour = calendar.component(.hour, from: start)
        let weekday = calendar.component(.weekday, from: start) // 1 = Sunday
        let today = calendar.startOfDay(for: input.now)
        let startDay = calendar.startOfDay(for: start)
        let daysAhead = calendar.dateComponents([.day], from: today, to: startDay).day ?? 0

        // Urgency dominates: every extra day of delay costs more than any
        // comfort bonus, otherwise long-horizon goals never get started.
        var score = 100.0 - Double(daysAhead) * 7.0

        if hour == 12 || hour == 13 { score -= 12 }        // lunch
        if hour >= 21 { score -= 18 }                       // too late to start
        if daysAhead > 0 && (weekday == 1 || weekday == 7) { score -= 4 }

        let freeMinutes = Int(slot.duration / 60)
        var reasons: [String] = []

        let crammed = input.busyEvents.contains {
            $0.goalID == candidate.goal.id && calendar.isDate($0.startAt, inSameDayAs: start)
        }
        if crammed { score -= 10 }

        var stateReason: String?
        switch state {
        case .tired:
            if (9...11).contains(hour) {
                score += 12
                stateReason = "你说自己累，所以放在精力相对好的上午"
            } else if hour >= 20 {
                score -= 15
            }
            if need <= 30 { score += 4 }
        case .busy:
            if need >= 60 { score -= 10 }
            if daysAhead == 0 { score += 6 }
        case .uninspired:
            if (10...16).contains(hour) {
                score += 10
                stateReason = "没灵感的时候，先给自己一段不被切碎的完整时间"
            }
            if slot.duration >= 90 * 60 { score += 8 }
            if slot.duration < TimeInterval((need + 30) * 60) { score -= 6 }
        case nil:
            break
        }

        if start.timeIntervalSince(input.now) <= 24 * 3600 { score += 4 }

        reasons.append("\(Self.dayLabel(start, calendar: calendar, now: input.now))\(Self.timeLabel(start, calendar: calendar))，这一步约需 \(need) 分钟，该时段连续空闲 \(freeMinutes) 分钟")
        if let stateReason { reasons.append(stateReason) }
        if daysAhead == 0 {
            reasons.append("今天就能推进，不用再往后拖")
        } else if !crammed {
            reasons.append("这个目标当天还没有安排，不会挤在一起")
        }
        if state != nil && freeMinutes >= need + 60 {
            reasons.append("前后还有富余，不容易被别的安排打断")
        }

        return (score, reasons)
    }

    static func dayLabel(_ date: Date, calendar: Calendar, now: Date) -> String {
        let today = calendar.startOfDay(for: now)
        let target = calendar.startOfDay(for: date)
        let days = calendar.dateComponents([.day], from: today, to: target).day ?? 0
        switch days {
        case 0: return "今天 "
        case 1: return "明天 "
        case 2: return "后天 "
        default:
            let components = calendar.dateComponents([.month, .day, .weekday], from: date)
            let names = ["周日", "周一", "周二", "周三", "周四", "周五", "周六"]
            let index = min(max((components.weekday ?? 1) - 1, 0), 6)
            return "\(components.month ?? 1)月\(components.day ?? 1)日 \(names[index]) "
        }
    }

    static func timeLabel(_ date: Date, calendar: Calendar) -> String {
        let components = calendar.dateComponents([.hour, .minute], from: date)
        return String(format: "%02d:%02d", components.hour ?? 0, components.minute ?? 0)
    }
}
